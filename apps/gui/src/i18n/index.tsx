type I18nContextValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: string, values?: Record<string, string | number>) => string };
const fallbackI18n: I18nContextValue = { locale: 'zh-CN', setLocale: () => undefined, t: (key, values) => (messages['zh-CN'][key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(values?.[name] ?? `{${name}}`)) };
const I18nContext = createContext<I18nContextValue>(fallbackI18n);

function detectLocale(): Locale {
  const saved = localStorage.getItem('omnistream.locale');
  if (saved === 'zh-CN' || saved === 'en-US') return saved;
  return 'zh-CN';
}

export function translate(key: string, values?: Record<string, string | number>) {
  const saved = localStorage.getItem('omnistream.locale');
  const locale: Locale = saved === 'en-US' ? 'en-US' : 'zh-CN';
  return (messages[locale][key] ?? messages['en-US'][key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(values?.[name] ?? `{${name}}`));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);
  const setLocale = (next: Locale) => { setLocaleState(next); localStorage.setItem('omnistream.locale', next); };
  const value = useMemo(() => ({ locale, setLocale, t: (key: string, values?: Record<string, string | number>) => (messages[locale][key] ?? messages['en-US'][key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(values?.[name] ?? `{${name}}`)) }), [locale]);
  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = 'OmniStream';
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) description.content = value.t('app.description');
  }, [locale, value]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
