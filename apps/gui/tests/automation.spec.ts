test('early approval waits for scheduled time and skipping another occurrence creates no business output', async ({ page }) => {
  const create = await fetch(endpoint + '/automations', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ title: 'Early approval', goal: 'Future business work', conversation: 'early-approval-inbox', schedule: { kind: 'interval', seconds: 3600 }, confirmation: { before_seconds: 4000, on_timeout: 'wait' } }) }).then(r => r.json());
  await page.addInitScript(url => { localStorage.setItem('omnistream.url', url); localStorage.setItem('omnistream.locale', 'zh-CN'); }, endpoint);
  await page.goto('/chat/early-approval-inbox');
  const card = page.getByRole('region', { name: '执行确认' }).first();
  await card.getByRole('button', { name: '确认本次执行' }).click();
  await expect(card.getByText('已确认，等待执行', { exact: true })).toBeVisible();
  await page.reload();
  await expect(card.getByText('已确认，等待执行', { exact: true })).toBeVisible();
  const read = async () => fetch(endpoint + '/automations').then(r => r.json()).then(items => items.find((item: { id: number }) => item.id === create.id));
  expect((await read()).runs).toHaveLength(0);
  const runResponse = await fetch(endpoint + '/automations/' + create.id + '/run', { method: 'POST' });
  expect(runResponse.ok).toBe(true);
  await expect(page.getByRole('region', { name: '执行确认' })).toHaveCount(2);
  const manualCard = page.getByRole('region', { name: '执行确认' }).last();
  await manualCard.getByRole('button', { name: '跳过本次执行' }).click();
  await expect.poll(async () => (await read()).runs[0]?.status).toBe('skipped');
  expect((await read()).runs[0].generation_output).toBeNull();
  await fetch(endpoint + '/automations/' + create.id + '/pause', { method: 'POST' });
});

test('unconfirmed-run option persists and executes the original content at the scheduled time', async ({ page }) => {
  await page.addInitScript(url => { localStorage.setItem('omnistream.url', url); localStorage.setItem('omnistream.locale', 'zh-CN'); }, endpoint);
  await page.goto('/chat/auto-timeout-inbox');
  await page.getByRole('button', { name: '长期任务', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '长期任务' });
  await dialog.getByLabel('任务标题').fill('未确认也按时执行测试');
  await dialog.getByLabel('委托内容').fill('Original scheduled content');
  const scheduled = new Date(Date.now() + 16000);
  await dialog.getByLabel('执行时间').fill(scheduled.toISOString().slice(11, 19));
  await dialog.getByLabel('UTC 偏移（分钟）').fill('0');
  await dialog.getByText('日历、统计窗口与投递', { exact: true }).click();
  await dialog.getByLabel('启用逐次确认').check();
  await dialog.getByLabel('到时未确认').selectOption('run');
  await expect(dialog.getByText('到时未确认则按原内容执行；已确认的修改才生效。正在讨论不会延迟执行。')).toBeVisible();
  await dialog.getByRole('button', { name: '创建并启用' }).click();
  const taskCard = dialog.locator('.automation-card').filter({ has: page.getByRole('heading', { name: '未确认也按时执行测试' }) });
  const card = taskCard.getByRole('region', { name: '执行确认' });
  await card.getByLabel('本次委托内容').fill('Unapproved changes must not execute');
  await card.getByRole('button', { name: '保存本次内容' }).click();
  const read = async () => fetch(endpoint + '/automations').then(r => r.json()).then(items => items.find((item: { title: string }) => item.title === '未确认也按时执行测试'));
  await expect.poll(async () => (await read()).confirmations[0].goal).toBe('Unapproved changes must not execute');
  expect((await read()).confirmation.on_timeout).toBe('run');
  expect((await read()).runs).toHaveLength(0);
  await expect.poll(async () => (await read()).runs[0]?.status, { timeout: 22000 }).toBe('succeeded');
  const item = await read();
  expect(item.runs).toHaveLength(1);
  expect(item.runs[0].context.goal).toBe('Original scheduled content');
  expect(item.runs[0].context.confirmation.execution_source).toBe('timeout');
  expect(item.confirmations[0].approved_at).toBeNull();
  await taskCard.getByRole('button', { name: '打开接收会话' }).click();
  const message = page.getByRole('region', { name: '执行确认' });
  await expect(message.getByText('已按未确认策略触发', { exact: true })).toBeVisible();
  await expect(message.getByText('本次执行内容', { exact: true })).toBeVisible();
  await expect(message.getByText('Original scheduled content', { exact: true })).toBeVisible();
  await page.reload();
  await expect(message.getByText('已按未确认策略触发', { exact: true })).toBeVisible();
});
